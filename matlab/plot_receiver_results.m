%% plot_receiver_results.m
% Plot receiver inputs, FIR outputs, and recovered bits.

clearvars;
clc;
close all;

input_table = readtable("input_samples.csv");
results = readtable("matlab_expected.csv");

valid = results.output_valid == 1;

figure("Name", "RF/DSP Receiver Reference Results");

subplot(3, 1, 1);

stem( ...
    input_table.sample_index, ...
    input_table.i_in, ...
    "filled" ...
    );

hold on;

stem( ...
    input_table.sample_index, ...
    input_table.q_in, ...
    "filled" ...
    );

grid on;
xlabel("Sample index");
ylabel("Input amplitude");
title("Input I/Q Samples");
legend("I input", "Q input");

subplot(3, 1, 2);

stem( ...
    results.sample_index(valid), ...
    results.fir_i(valid), ...
    "filled" ...
    );

hold on;

stem( ...
    results.sample_index(valid), ...
    results.fir_q(valid), ...
    "filled" ...
    );

grid on;
xlabel("Sample index");
ylabel("Filtered amplitude");
title("Valid FIR Outputs");
legend("Filtered I", "Filtered Q");

subplot(3, 1, 3);

stairs( ...
    results.sample_index(valid), ...
    results.bit_msb(valid), ...
    "LineWidth", ...
    1.5 ...
    );

hold on;

stairs( ...
    results.sample_index(valid), ...
    results.bit_lsb(valid), ...
    "LineWidth", ...
    1.5 ...
    );

grid on;
ylim([-0.2, 1.2]);
xlabel("Sample index");
ylabel("Bit value");
title("QPSK Demapper Outputs");
legend("Bit MSB", "Bit LSB");